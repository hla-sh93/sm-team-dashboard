/**
 * تفريغ كاش الصفحات — وفشله ما بيقلب العملية فشلاً.
 *
 * `revalidatePath` بترمي إذا انندهت من برّا طلب Next (سكربت، فحص، أي مسار مو
 * طالع من متصفّح). وهي بتنندى **بعد** ما الداتا تنكتب وجوّا نفس `try`، فرميتها
 * كانت تطلع للقائدة «فشل …» بينما الكتابة صارت فعلاً — أخطر جواب ممكن، لأنها
 * بتعيد الضغط على شي تمّ.
 *
 * صار فعلاً بمسارين: استيراد الخطة (الحمولة انكتبت والجواب «فشل تطبيق خطة
 * المحتوى») وإعادة الجدولة (٢٩٢ كرت انكتبوا والجواب «فشل توليد الجدول»). وكان
 * لساتو موجوداً بـ٣٥ نداء تانية بالشركات والمهام وتلغرام والموظفين.
 *
 * كل مسار بيكتب لازم ينده هاد بدل `revalidatePath` مباشرةً.
 */
import { revalidatePath } from "next/cache";

/** بيفرّغ كاش الشجرة كلها — الموظف (الجذر) والإدارة (/admin) سوا. */
export function revalidateAll() {
  revalidateSafely("/", "layout");
}

/** تفريغ مسار محدَّد، بلا ما يرمي. */
export function revalidateSafely(path: string, type?: "layout" | "page") {
  try {
    revalidatePath(path, type);
  } catch {
    // ما في طلب Next — ما في كاش نفرّغه. الكتابة صارت، وهي يلي بتهمّ.
  }
}
