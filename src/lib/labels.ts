export const LEAD_TITLE = "مسؤولة الفريق";
/** للجمل: «الكرت بيسكّره صاحبه أو المسؤولة». */
export const LEAD_SHORT = "المسؤولة";

/**
 * دور «مسؤول الفريق» — كل الصيغ يلي انكتبت أو ممكن تنكتب: المفتاح `lead`، «تيم ليدر» المخزّن
 * نصّاً (حلا: «تيم ليدر + نص مصمم»)، و«قائد»، والمسمّى الجديد «مسؤول/ة الفريق» أو «مشرف/ة».
 * «مسؤول حسابات» **مو** مسؤول فريق.
 */
export const isLeadRole = (role: string | null | undefined): boolean =>
  /ليدر|lead|قائد|مسؤول(?:ة)?\s+(?:ال)?فريق|مشرف/i.test(role ?? "");
