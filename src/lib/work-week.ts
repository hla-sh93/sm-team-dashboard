/**
 * يوم عطلة الفريق — مشتقّ من أيام دوام الناس، مو من رقم يوم مكتوب بالكود.
 *
 * القائدة (٥/٩/٢٠٢٦): «الجمعة والسبت ما لازم يكون في تقارير مهام — التيم معطّل».
 * وصل بريف «تفاصيل السبت ٥/٩» فيه شغل لسبع أشخاص كلهم بعطلة: موجة ٧:٤٥ عندها
 * فلتر أيام الدوام، وموجة ٨:٠٠ ما كان عندها ولا تقرير المساء.
 *
 * ليش مشتقّ لا مثبّت: أسبوع العمل تغيّر مرّة (السيلز والفريلانس كانوا سبت→أربعاء
 * وصاروا أحد→خميس). رقم مكتوب بالكود بيصير كذبة بصمت أول ما يتغيّر دوام حدا؛
 * القاعدة المشتقّة بتتبع الداتا لحالها.
 */

import { parseWorkDays } from "@/lib/dates";

export type WorkDaysHolder = { workDays: string | number[] | null };

/**
 * صحيح لما **ولا حدا** بالفريق دوامه بهاد اليوم.
 *
 * لائحة فاضية بترجّع `false` عن قصد: «ما في موظفين» مو «الكل بعطلة»، وما بيصحّ
 * سكوت التقارير كلها لأن جدول الموظفين ما انقرا.
 */
export function isTeamOffDay(team: WorkDaysHolder[], date: Date): boolean {
  if (!team.length) return false;
  const day = date.getDay();
  return !team.some((member) => parseWorkDays(member.workDays).includes(day));
}
